# SELFCHECK. The hand-written metadata in this file is the only part that can
# be wrong without anything failing, so it is the only part with a test.
# --------------------------------------------------------------------------

def selfcheck(board=None):
    # board is threaded through for the same reason stage_model takes it: the
    # metadata this validates (stages, asks, node coverage) does not depend on
    # what the platform is doing, and probing the live platform to check a
    # hand-written list is both slow and non-deterministic.
    m = stage_model(board)       # raises on any node/stage coverage gap
    problems, notes = [], []

    node_ids = {n["id"] for l in m["lines"] for s in l["stages"] for n in s["nodes"]}
    seen = set()
    for a in ASKS:
        if a["id"] in seen:
            problems.append(f"ask id 重複：{a['id']}")
        seen.add(a["id"])
        if a["node"] not in node_ids:
            problems.append(f"ask {a['id']} 綁在不存在的節點 {a['node']}")
        if a["owner"] not in OWNER_LABEL:
            problems.append(f"ask {a['id']} 的 owner 不合法：{a['owner']}")
        if a["owner"] == "eng":
            problems.append(f"ask {a['id']} 的 owner 是 eng——eng 是沒有 ask 時的預設，"
                            "寫成 ask 表示它其實在等某個人")
        if not a["options"]:
            problems.append(f"ask {a['id']} 沒有可選項——只描述問題不給選項，讀的人無法決定")
        ref = os.path.join(REPO_ROOT, a["ref"])
        if not os.path.exists(ref):
            problems.append(f"ask {a['id']} 指向不存在的檔案 {a['ref']}")

    live = {a["id"] for a in m["asks"]}
    for a in ASKS:
        if a["id"] not in live:
            notes.append(f"ask {a['id']} 目前沒有對應到任何現況"
                         f"（節點 {a['node']} 已正常，或 detail 不再包含 \"{a['when']}\"）"
                         "——條件已消失，這筆該刪或該改")

    for l in m["lines"]:
        for s in l["stages"]:
            if not s["why"].strip():
                problems.append(f"{l['name']} · {s['name']} 沒有說明")

    for p in problems:
        print(f"FAIL  {p}")
    for n in notes:
        print(f"NOTE  {n}")
    if not problems and not notes:
        print("OK    節點覆蓋完整，ASKS 全部對應到現況")
    elif not problems:
        print(f"OK    無錯誤；{len(notes)} 筆 ask 待清理")
    return 1 if problems else 0


