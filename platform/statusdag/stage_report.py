# --------------------------------------------------------------------------
# THE MODEL. Everything below renders this and nothing else.
# --------------------------------------------------------------------------

def stage_state(nodes):
    """Worst node wins. A stage with one failing node is not 'mostly fine'."""
    if not nodes:
        return dag.UNKNOWN
    return max((n["state"] for n in nodes), key=lambda s: STATE_ORDER[s])


def matching_asks(nodes):
    """Asks whose bound condition is TRUE RIGHT NOW, for these nodes.

    Both halves are required. A node being amber is not enough -- the detail
    string has to still say what the ask claims it says. `scheduler` going amber
    for an unrelated reason must not resurrect the offsite question next to it.
    """
    out = []
    for a in ASKS:
        for n in nodes:
            if n["id"] != a["node"] or n["state"] not in ACTIONABLE:
                continue
            if a["when"] in n["detail"]:
                out.append(dict(a, node_label=n["label"], node_detail=n["detail"]))
            break
    return out


def stage_model():
    """Build the single source of truth. Raises rather than renders a page that
    silently omits a node -- a report missing a stage looks exactly like a
    report where that stage is fine."""
    board = dag.build()
    by_id = {n["id"]: n for n in board["nodes"]}

    declared = set()
    for _, _, _, stages in LINES:
        for st in stages:
            declared |= set(st["nodes"])
    missing = sorted(set(by_id) - declared)
    phantom = sorted(declared - set(by_id))
    if missing:
        raise SystemExit(
            "stage_report: dag.py has nodes this report does not show: "
            + ", ".join(missing)
            + "\nAdd them to LINES. A node that is not on any stage is invisible "
              "here, and invisible reads identically to healthy.")
    if phantom:
        raise SystemExit(
            "stage_report: LINES references nodes dag.py does not produce: "
            + ", ".join(phantom))

    lines = []
    all_asks = []
    for line_id, line_name, line_sub, stages in LINES:
        smodels = []
        for st in stages:
            nodes = [by_id[i] for i in st["nodes"]]
            state = stage_state(nodes)
            asks = matching_asks(nodes) if state in ACTIONABLE else []
            owner = asks[0]["owner"] if asks else ("eng" if state in ACTIONABLE else None)
            culprits = [n for n in nodes if n["state"] in ACTIONABLE]
            smodels.append({
                "name": st["name"], "why": st["why"], "state": state,
                "owner": owner, "asks": asks,
                "nodes": [{"id": n["id"], "label": n["label"],
                           "state": n["state"], "detail": n["detail"]}
                          for n in nodes],
                "culprits": [{"id": n["id"], "label": n["label"],
                              "state": n["state"], "detail": n["detail"]}
                             for n in culprits],
            })
            for a in asks:
                all_asks.append(dict(a, line=line_name, stage=st["name"], state=state))
        lines.append({
            "id": line_id, "name": line_name, "subtitle": line_sub,
            "stages": smodels,
            "green": sum(1 for s in smodels if s["state"] == dag.OK),
            "superseded": sum(1 for s in smodels if s["state"] == dag.SUPERSEDED),
            "total": len(smodels),
        })

    attention = [(l, s) for l in lines for s in l["stages"] if s["state"] in ACTIONABLE]
    by_owner = {o: [] for o in OWNER_ORDER}
    for l, s in attention:
        by_owner[s["owner"]].append({"line": l["name"], **s})

    return {
        "schema": SCHEMA,
        "generated_at": board["generated_at"],
        "verdict": board["verdict"],
        "totals": {
            "green": sum(l["green"] for l in lines),
            "stages": sum(l["total"] for l in lines),
            "superseded": sum(l["superseded"] for l in lines),
            "attention": len(attention),
            "by_owner": {o: len(v) for o, v in by_owner.items()},
        },
        "headline": headline(lines, by_owner),
        "by_owner": by_owner,
        "lines": lines,
        "asks": all_asks,
    }


def headline(lines, by_owner):
    """One sentence, written for someone who will read exactly one sentence.

    It leads with what is being ASKED OF THE READER, not with the tally: a
    reviewer who reads '17/19 綠' and stops has learned nothing about the thing
    that is waiting on them.
    """
    green = sum(l["green"] for l in lines)
    total = sum(l["total"] for l in lines)
    sup = sum(l["superseded"] for l in lines)
    tail = f"{green}/{total} 階段正常" + (f"，{sup} 已遷移至 K8s" if sup else "")
    parts = []
    for o in ("decision", "external", "research"):
        if by_owner[o]:
            parts.append(f"{len(by_owner[o])} 項{OWNER_LABEL[o]}")
    eng = len(by_owner["eng"])
    if not parts and not eng:
        return f"沒有需要決定的事項；{tail}。"
    lead = "、".join(parts) if parts else "沒有需要您決定的事項"
    if eng:
        lead += f"；另有 {eng} 項工程自理"
    return f"{lead}。{tail}。"


# --------------------------------------------------------------------------
# RENDERER: markdown digest, for an AI or a chat message.
#
# Sized on purpose. Non-green stages get their culprits and their ask; green
# stages collapse to one table row. The reader that needs every node's detail
# has the JSON; what this one needs is to fit in a prompt and still contain
# every fact required to answer "what is wrong and whose move is it".
# --------------------------------------------------------------------------

def render_markdown(m):
    t = m["totals"]
    # OKF v0.1 frontmatter, emitted rather than hand-written. The repo's other
    # markdown carries it so an agent can consume the tree as a knowledge
    # bundle (platform/docs/okf_check.py enforces it); a generated file that
    # opted out would be the one document in the bundle an agent has to open
    # and parse specially. `review` is the spec-local type for a
    # point-in-time assessment, which is exactly what this is.
    out = [
        "---",
        "type: review",
        "title: 三線階段燈號",
        'description: "Live stage-level status for DevOps, DataOps and MLOps, '
        'grouped by whose move it is. Generated from probes, never hand-edited."',
        "tags:",
        "  - status",
        "  - devops",
        "  - dataops",
        "  - mlops",
        f"timestamp: {m['generated_at']}",
        "generator: platform/statusdag/stage_report.py",
        "---",
        "",
        "# 三線階段燈號",
        "",
        "<!-- 這份檔案是產生的，不要手動編輯：下一次排程執行會整份覆蓋。 -->",
        "",
        f"- schema: `{m['schema']}`",
        f"- generated: `{m['generated_at']}`",
        f"- verdict: `{m['verdict']}`",
        f"- 階段: {t['green']}/{t['stages']} 正常"
        + (f"，{t['superseded']} 已被取代（遷移至 K8s）" if t["superseded"] else ""),
        "",
        f"> {m['headline']}",
        "",
        "每一盞燈都是本次執行的實測（查資料庫、問叢集、讀證據檔），不是文件記載。",
        "階段只有在底下每個節點都正常時才是綠的。",
        "",
    ]

    for owner in OWNER_ORDER:
        items = m["by_owner"][owner]
        out.append(f"## {OWNER_LABEL[owner]}（{len(items)}）")
        out.append("")
        if not items:
            out += ["（無）", ""]
            continue
        for s in items:
            out.append(f"### {s['line']} · {s['name']} — {STATE_LABEL[s['state']]}")
            for c in s["culprits"]:
                out.append(f"- `{c['id']}` {c['label']}：{c['detail']}")
            for a in s["asks"]:
                out.append(f"- **問題**：{a['ask']}")
                for opt in a["options"]:
                    out.append(f"  - 可選：{opt}")
                out.append(f"  - 參考：`{a['ref']}`（ask id `{a['id']}`）")
            out.append("")

    out += ["## 全部階段", "", "| 線 | 階段 | 狀態 | 這一段負責什麼 |",
            "|---|---|---|---|"]
    for l in m["lines"]:
        for s in l["stages"]:
            out.append(f"| {l['name']} | {s['name']} | {STATE_LABEL[s['state']]} | {s['why']} |")
    out += ["",
            "產生自 `platform/statusdag/stage_report.py`；探測邏輯 `platform/statusdag/dag.py`。",
            "完整節點資料見 `docs/Stage-Report.json`，圖與看板見 `docs/Stage-Report.html`。",
            ""]
    return "\n".join(out)


def render_json(m):
    return json.dumps(m, ensure_ascii=False, indent=2) + "\n"


# --------------------------------------------------------------------------
# SELFCHECK. The hand-written metadata in this file is the only part that can
# be wrong without anything failing, so it is the only part with a test.
# --------------------------------------------------------------------------

def selfcheck():
    m = stage_model()            # raises on any node/stage coverage gap
    problems, notes = [], []

    node_ids = {n["id"] for l in m["lines"] for s in l["stages"] for n in s["nodes"]}
    seen = set()
    for a in ASKS:
        if a["id"] in seen:
            problems.append(f"ask id 重複：{a['id']}")
        seen.add(a["id"])
        if a["node"] not in node_ids:
            problems.append(f"ask {a['id']} 綁在不存在的節點 {a['node']}")
        if a["owner"] not in OWNER_LABEL:
            problems.append(f"ask {a['id']} 的 owner 不合法：{a['owner']}")
        if a["owner"] == "eng":
            problems.append(f"ask {a['id']} 的 owner 是 eng——eng 是沒有 ask 時的預設，"
                            "寫成 ask 表示它其實在等某個人")
        if not a["options"]:
            problems.append(f"ask {a['id']} 沒有可選項——只描述問題不給選項，讀的人無法決定")
        ref = os.path.join(REPO_ROOT, a["ref"])
        if not os.path.exists(ref):
            problems.append(f"ask {a['id']} 指向不存在的檔案 {a['ref']}")

    live = {a["id"] for a in m["asks"]}
    for a in ASKS:
        if a["id"] not in live:
            notes.append(f"ask {a['id']} 目前沒有對應到任何現況"
                         f"（節點 {a['node']} 已正常，或 detail 不再包含 \"{a['when']}\"）"
                         "——條件已消失，這筆該刪或該改")

    for l in m["lines"]:
        for s in l["stages"]:
            if not s["why"].strip():
                problems.append(f"{l['name']} · {s['name']} 沒有說明")

    for p in problems:
        print(f"FAIL  {p}")
    for n in notes:
        print(f"NOTE  {n}")
    if not problems and not notes:
        print("OK    節點覆蓋完整，ASKS 全部對應到現況")
    elif not problems:
        print(f"OK    無錯誤；{len(notes)} 筆 ask 待清理")
    return 1 if problems else 0


