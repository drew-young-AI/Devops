# --------------------------------------------------------------------------
# ASKS -- the only hand-written judgement in this file, and it is deliberately
# built so that it cannot go stale silently.
#
# The problem being solved: an amber list that mixes "engineering is on it"
# with "this is waiting on a decision only you can make" forces the reviewer to
# read every row to find the one that is theirs. Grouping by WHO OWNS THE NEXT
# MOVE is the difference between a list that gets acted on and one that gets
# skimmed.
#
# The rot hazard is obvious: a hand-written note attached to a stage stays
# attached after the reason for it is gone, and then the page is confidently
# wrong. Two mechanisms against that, and they matter more than the text:
#
#   1. An ask is BOUND TO A LIVE CONDITION -- a node id plus a substring that
#      must appear in that node's CURRENT detail. It renders only while the
#      platform is actually reporting that condition. It cannot outlive it.
#   2. --selfcheck reports asks matching nothing, so a resolved one surfaces as
#      a deletion candidate instead of sitting there forever.
#
# `owner` is who makes the next move, not who is to blame:
#   decision  waiting on the platform owner to choose. Engineering cannot
#             proceed by working harder.
#   external  waiting on an outside body. Not ours to schedule.
#   research  an open research result, not a defect. "Fixing" it is a category
#             error -- the honest report is that the model lost.
# Anything non-green with NO matching ask is `eng` by default: nobody is being
# asked for anything, engineering owns it.
# --------------------------------------------------------------------------

