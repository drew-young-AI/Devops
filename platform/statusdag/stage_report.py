#!/usr/bin/env python3
"""Stage-level status for a stage review -- rendered for three different readers.

WHY THIS EXISTS SEPARATELY FROM dag.py's OWN PAGE.

dag.py renders an engineer's board: every node, every container, one row each.
That is the right shape for the person on call and the wrong shape for a stage
review. "Grafana 檢視 — running" tells a reviewer nothing they can act on; it is
tool status, not stage status.

So this reorganises the SAME live probes into the unit a reviewer thinks in --
the STAGE -- and pairs each line with its architecture and flow diagram. A stage
is green only if every node under it is green, and it names which node is
responsible when it is not. Nothing here is hand-written status: every light
comes from dag.build(), which queries the database and the cluster at the moment
this runs.

THREE READERS, THREE RENDERINGS, ONE MODEL.

The failure this file is built against: one artifact serving three audiences
serves none of them. So stage_model() is the single source of truth and there
are three renderers over it, each shaped by what its reader actually does next.

  html  人類 / 長官 -- lights, diagrams, and A DECISION LIST SEPARATED FROM THE
        ENGINEERING LIST. A flat amber list makes a reviewer read nineteen rows
        to find the one that is waiting on them. That is the difference between
        a report that gets acted on and one that gets skimmed.
  json  machine -- schema-versioned, complete, stable key names. For anything
        that wants to assert on the state rather than look at it.
  md    AI / chat -- a few KB, non-green stages expanded and green ones rolled
        up to one line. An 80 KB HTML page with six inlined SVGs is not an
        input; it is a denial-of-service on a context window.

WHY IT IS GENERATED RATHER THAN WRITTEN.

A written status document is accurate on the day it is written and misleading
from the next. This one is regenerated by the scheduler, and every rendering
carries the timestamp it was generated at, so a stale copy announces itself.

Usage:
  stage_report.py                  # all three formats into docs/
  stage_report.py --format md      # just the digest, to stdout
  stage_report.py --selfcheck      # validate the hand-written metadata
"""
