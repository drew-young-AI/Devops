STATE_ORDER = {dag.OK: 0, dag.SUPERSEDED: 1, dag.WARN: 2, dag.UNKNOWN: 3, dag.FAIL: 4}
STATE_LABEL = {dag.OK: "正常", dag.SUPERSEDED: "已被取代", dag.WARN: "注意",
               dag.UNKNOWN: "無法判定", dag.FAIL: "失敗"}
# A superseded stage is not something to act on -- it is a stage that moved.
# Keeping it out of the attention list is the whole reason the state exists:
# five permanently-amber migration rows were crowding out the two that need a
# decision, and an attention list nobody can act on stops being read.
ACTIONABLE = (dag.WARN, dag.UNKNOWN, dag.FAIL)


def blocks_completion(node):
    """Does this node hold a line back, whatever colour it is showing?

    ACTIONABLE alone was not the right set. A node that is SUPERSEDED and
    still WAITING for its replacement (`llmreview`) counts against completion
    below -- it is in `blocking` -- but it was invisible to the ask matcher,
    which only looked at actionable states. The consequence was quiet and
    wrong: with no ask attached, the owner fell through to the `eng` default,
    so the board said engineering was sitting on something that in fact needed
    a decision nobody had been asked for.

    Retired-and-replaced nodes are NOT blocking (their work moved to a live
    node here), which is the same split the completion block makes, by the
    same heuristic, stated in one place.
    """
    if node["state"] in ACTIONABLE:
        return True
    return node["state"] == dag.SUPERSEDED and "待" in (node.get("detail") or "")

assert set(STATE_ORDER) == set(STATE_LABEL), "state tables disagree"
assert set(STATE_ORDER) == set(dag.RANK), "stage_report and dag disagree on the state set"


# --------------------------------------------------------------------------
# THE MODEL. Everything below renders this and nothing else.
# --------------------------------------------------------------------------

def stage_state(nodes):
    """Worst node wins. A stage with one failing node is not 'mostly fine'."""
    if not nodes:
        return dag.UNKNOWN
    return max((n["state"] for n in nodes), key=lambda s: STATE_ORDER[s])


def matching_asks(nodes):
    """Asks whose bound condition is TRUE RIGHT NOW, for these nodes.

    Both halves are required. A node being amber is not enough -- the detail
    string has to still say what the ask claims it says. `scheduler` going amber
    for an unrelated reason must not resurrect the offsite question next to it.
    """
    out = []
    for a in ASKS:
        for n in nodes:
            if n["id"] != a["node"] or not blocks_completion(n):
                continue
            if a["when"] in n["detail"]:
                out.append(dict(a, node_label=n["label"], node_detail=n["detail"]))
            break
    return out


# How old a supplied board may be before rendering it is a lie. Fifteen minutes
# is the scheduler's own interval for dag.py, so anything older than twice that
# is a board nobody refreshed.
BOARD_MAX_AGE_SECONDS = 1800


def load_board(path):
    """Read a board produced by `dag.py --json`, and refuse a stale one.

    WHY THIS EXISTS. dag.build() probes the live platform: it talks to Docker,
    Postgres, kubectl, Prometheus and the scheduler, and it takes roughly one
    and a half minutes. Two scheduled jobs -- `dag` and `stagereport` -- each
    called it every 15 minutes, so the platform was probed twice per cycle and
    the two artefacts described two DIFFERENT moments. On 2026-09-08 that
    showed up as the board saying FAILED and Stage-Report.json saying DEGRADED
    three minutes apart, from the same underlying state.

    WHY IT REFUSES A STALE FILE. A renderer that will read any JSON on disk is
    a renderer that will happily present last week as today, and a stale status
    page is the specific failure this repo has already paid for twice. So the
    age is checked and the refusal names the age.
    """
    with open(path, encoding="utf-8") as fh:
        board = json.load(fh)
    for key in ("nodes", "verdict"):
        if key not in board:
            raise SystemExit(f"stage_report: {path} has no '{key}' -- that is "
                             f"not a board from dag.py --json")
    stamp = board.get("generated_at")
    if not stamp:
        raise SystemExit(f"stage_report: {path} carries no generated_at, so "
                         f"its age cannot be checked. Refusing: an undatable "
                         f"board is indistinguishable from an old one.")
    try:
        when = datetime.strptime(stamp, "%Y-%m-%dT%H:%M:%SZ").replace(
            tzinfo=timezone.utc)
    except ValueError:
        raise SystemExit(f"stage_report: cannot parse generated_at {stamp!r}")
    age = (datetime.now(timezone.utc) - when).total_seconds()
    if age > BOARD_MAX_AGE_SECONDS:
        raise SystemExit(
            f"stage_report: {path} was generated {int(age)}s ago, over the "
            f"{BOARD_MAX_AGE_SECONDS}s limit. Re-run dag.py --json, or drop "
            f"--from-board and let this probe the platform itself.")
    return board


def stage_model(board=None):
    """Build the single source of truth. Raises rather than renders a page that
    silently omits a node -- a report missing a stage looks exactly like a
    report where that stage is fine."""
    board = dag.build() if board is None else board
    by_id = {n["id"]: n for n in board["nodes"]}

    declared = set()
    for _, _, _, stages in LINES:
        for st in stages:
            declared |= set(st["nodes"])
    missing = sorted(set(by_id) - declared)
    phantom = sorted(declared - set(by_id))
    if missing:
        raise SystemExit(
            "stage_report: dag.py has nodes this report does not show: "
            + ", ".join(missing)
            + "\nAdd them to LINES. A node that is not on any stage is invisible "
              "here, and invisible reads identically to healthy.")
    if phantom:
        raise SystemExit(
            "stage_report: LINES references nodes dag.py does not produce: "
            + ", ".join(phantom))

    lines = []
    all_asks = []
    for line_id, line_name, line_sub, stages in LINES:
        smodels = []
        for st in stages:
            nodes = [by_id[i] for i in st["nodes"]]
            state = stage_state(nodes)
            blocking_nodes = [n for n in nodes if blocks_completion(n)]
            asks = matching_asks(nodes) if blocking_nodes else []
            owner = asks[0]["owner"] if asks else ("eng" if blocking_nodes else None)
            culprits = [n for n in nodes if n["state"] in ACTIONABLE]
            smodels.append({
                "name": st["name"], "why": st["why"], "state": state,
                "owner": owner, "asks": asks,
                "nodes": [{"id": n["id"], "label": n["label"],
                           "state": n["state"], "detail": n["detail"]}
                          for n in nodes],
                "culprits": [{"id": n["id"], "label": n["label"],
                              "state": n["state"], "detail": n["detail"]}
                             for n in culprits],
            })
            for a in asks:
                all_asks.append(dict(a, line=line_name, stage=st["name"], state=state))
        # NODE-LEVEL COMPLETION, WITH ITS DENOMINATOR STATED (2026-09-09).
        #
        # WHY THIS IS SEPARATE FROM THE STAGE COUNTS ABOVE.
        #
        # `green`/`total` above count STAGES. A stage is amber if any node in it
        # is, so DevOps reads 3/9 while its nodes read 16/24. Both are true and
        # they are different questions -- and a reader who does not know which
        # one they are looking at gets 33% or 67% for the same platform.
        #
        # The user's own landing standard is "all three lines at 90%", so the
        # number that standard is measured against has to exist, be generated,
        # and say what it divides by. A hand-written percentage in a document
        # is stale the next time anything moves.
        #
        # SUPERSEDED IS SPLIT, because it hides two different things:
        #   - `retired`: the node was verified and its job moved somewhere that
        #     is itself a live node here (CI/scan/registry/production-like all
        #     moved onto Kubernetes). Counting these as incomplete says work is
        #     missing when it is being done by its replacement.
        #   - `awaiting`: the node was retired and nothing replaced it yet
        #     (`llmreview` still has no Kubernetes artefact wired in).
        # The split is by whether the node's own detail says it is waiting.
        # It is a heuristic, and it is stated here rather than hidden: a reader
        # who disagrees can recount from `nodes` in this same document.
        lnodes = [n for st in smodels for n in st["nodes"]]
        # `or "eng"` at the read site: a stage with no declared owner yields
        # None, and an unowned blocker is engineering work by default --
        # never "nobody's".
        owner_of = {n["id"]: st["owner"] for st in smodels for n in st["nodes"]}
        sup_nodes = [n for n in lnodes if n["state"] == dag.SUPERSEDED]
        awaiting = [n for n in sup_nodes if blocks_completion(n)]
        retired = [n for n in sup_nodes if n not in awaiting]
        n_ok = sum(1 for n in lnodes if n["state"] == dag.OK)
        n_total = len(lnodes)
        lines.append({
            "id": line_id, "name": line_name, "subtitle": line_sub,
            "stages": smodels,
            "green": sum(1 for s in smodels if s["state"] == dag.OK),
            "superseded": sum(1 for s in smodels if s["state"] == dag.SUPERSEDED),
            "total": len(smodels),
            "completion": {
                "denominator": "nodes",
                "nodes_total": n_total,
                "nodes_ok": n_ok,
                "nodes_superseded_retired": len(retired),
                "nodes_superseded_awaiting": len(awaiting),
                "nodes_actionable": n_total - n_ok - len(sup_nodes),
                # STRICT counts only ok. GENEROUS also credits nodes whose job
                # is demonstrably being done by a live replacement. The gap
                # between the two IS the argument, so both are published and
                # neither is called "the" completion.
                "pct_strict": round(100.0 * n_ok / n_total, 1) if n_total else 0.0,
                "pct_crediting_retired": (
                    round(100.0 * (n_ok + len(retired)) / n_total, 1)
                    if n_total else 0.0),
                # THE OWNER TRAVELS WITH THE BLOCKER, and it is declared in
                # LINES rather than judged here.
                #
                # This is what makes a completion target usable instead of
                # motivating. Of the four things holding DevOps below its
                # target, one waits on a decision, two are engineering, and one
                # is retired-awaiting-reconnection; DataOps' single blocker is
                # `external` (a national health agency has not published the
                # calendar mapping) and MLOps' is `research` (the model really
                # does lose to persistence at t+1).
                #
                # ONLY `eng` IS WORK THIS REPOSITORY CAN CLOSE BY ITSELF.
                # Driving `external` or `research` green would mean either
                # waiting on someone else or making a node stop saying a true
                # thing -- and a board that goes green by no longer reporting
                # the bad news is the failure this whole platform is built
                # against. So the split is published next to the percentage.
                "blocking": [
                    {"id": n["id"], "state": n["state"],
                     "owner": (owner_of.get(n["id"]) or "eng"),
                     "detail": (n.get("detail") or "")[:70]}
                    for n in lnodes
                    if n["state"] != dag.OK and n not in retired],
                "blocking_by_owner": {
                    o: sum(1 for n in lnodes
                           if n["state"] != dag.OK and n not in retired
                           and (owner_of.get(n["id"]) or "eng") == o)
                    for o in OWNER_ORDER
                    if any(n["state"] != dag.OK and n not in retired
                           and (owner_of.get(n["id"]) or "eng") == o
                           for n in lnodes)},
            },
        })

    attention = [(l, s) for l in lines for s in l["stages"] if s["state"] in ACTIONABLE]
    by_owner = {o: [] for o in OWNER_ORDER}
    for l, s in attention:
        by_owner[s["owner"]].append({"line": l["name"], **s})

    return {
        "schema": SCHEMA,
        "generated_at": board["generated_at"],
        "verdict": board["verdict"],
        "totals": {
            "green": sum(l["green"] for l in lines),
            "stages": sum(l["total"] for l in lines),
            "superseded": sum(l["superseded"] for l in lines),
            "attention": len(attention),
            "by_owner": {o: len(v) for o, v in by_owner.items()},
        },
        "headline": headline(lines, by_owner),
        "by_owner": by_owner,
        "lines": lines,
        "asks": all_asks,
    }


def headline(lines, by_owner):
    """One sentence, written for someone who will read exactly one sentence.

    It leads with what is being ASKED OF THE READER, not with the tally: a
    reviewer who reads '17/19 綠' and stops has learned nothing about the thing
    that is waiting on them.
    """
    green = sum(l["green"] for l in lines)
    total = sum(l["total"] for l in lines)
    sup = sum(l["superseded"] for l in lines)
    tail = f"{green}/{total} 階段正常" + (f"，{sup} 已遷移至 K8s" if sup else "")
    parts = []
    for o in ("decision", "external", "research"):
        if by_owner[o]:
            parts.append(f"{len(by_owner[o])} 項{OWNER_LABEL[o]}")
    eng = len(by_owner["eng"])
    if not parts and not eng:
        return f"沒有需要決定的事項；{tail}。"
    lead = "、".join(parts) if parts else "沒有需要您決定的事項"
    if eng:
        lead += f"；另有 {eng} 項工程自理"
    return f"{lead}。{tail}。"


